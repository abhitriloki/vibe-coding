// @desc    Update user API keys
// @route   PUT /api/auth/api-keys
// @access  Private
export const updateApiKeys = async (req, res) => {
  try {
    const { openRouter, openAI, anthropic, preferredProvider } = req.body;

    const user = await User.findById(req.user._id);

    if (openRouter !== undefined) user.apiKeys.openRouter = openRouter;
    if (openAI !== undefined) user.apiKeys.openAI = openAI;
    if (anthropic !== undefined) user.apiKeys.anthropic = anthropic;
    if (preferredProvider) user.preferredProvider = preferredProvider;

    await user.save();

    res.json({
      message: 'API keys updated successfully',
      preferredProvider: user.preferredProvider
    });
  } catch (error) {
    console.error(error);
    res.status(500).json({ message: 'Server error', error: error.message });
  }
};

